<?php

namespace App\Models;

use App\Support\TemplateRegistry;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Support\Facades\Storage;

class Template extends Model
{
    protected $fillable = [
        'category_id', 'name', 'slug', 'layout', 'tagline', 'description', 'preview_path',
        'theme', 'design', 'max_photos', 'is_premium', 'is_featured', 'is_active', 'sort_order',
    ];

    protected function casts(): array
    {
        return [
            'theme' => 'array',
            'design' => 'array',
            'is_premium' => 'boolean',
            'is_featured' => 'boolean',
            'is_active' => 'boolean',
        ];
    }

    public function getRouteKeyName(): string
    {
        return 'slug';
    }

    public function category(): BelongsTo
    {
        return $this->belongsTo(Category::class);
    }

    public function fields(): HasMany
    {
        return $this->hasMany(TemplateField::class)->orderBy('sort_order')->orderBy('id');
    }

    public function pages(): HasMany
    {
        return $this->hasMany(Page::class);
    }

    public function scopeActive(Builder $q): Builder
    {
        return $q->where('is_active', true)
            ->whereHas('category', fn ($c) => $c->where('is_active', true))
            ->orderBy('sort_order')->orderBy('id');
    }

    public function previewUrl(): ?string
    {
        if (! $this->preview_path) {
            return null;
        }

        return str_starts_with($this->preview_path, 'images/')
            ? asset($this->preview_path)
            : Storage::disk('public')->url($this->preview_path);
    }

    /** Theme = layout defaults, overridden by this template's saved theme. */
    /** Two phone screenshots for cards: the closed cover and the opened page (generated by tools/previews/phones.cjs). */
    public function phoneShots(): ?array
    {
        $cover = "images/previews/phone/{$this->slug}-cover.webp";
        $inside = "images/previews/phone/{$this->slug}-inside.webp";
        if (! file_exists(public_path($cover))) {
            return null;
        }

        return ['cover' => asset($cover), 'inside' => file_exists(public_path($inside)) ? asset($inside) : asset($cover)];
    }

    /** What the site's live-preview popup needs to show this template. */
    public function previewPayload(): array
    {
        $music = TemplateRegistry::MUSIC[$this->sampleContent()['music'] ?? ''] ?? null;

        return [
            'name' => $this->name,
            'category' => (string) $this->category?->displayName(),
            'description' => $this->description,
            'render' => route('templates.render', $this),
            'show' => route('templates.show', $this),
            'order' => route('order.create', ['template' => $this->slug]),
            'music' => $music ? $music['title'] : null,
        ];
    }

    public function resolvedTheme(array $overrides = []): array
    {
        $defaults = TemplateRegistry::layout($this->layout)['theme'] ?? [];

        return array_merge($defaults, array_filter($this->theme ?? [], fn ($v) => $v !== null && $v !== ''), array_filter($overrides, fn ($v) => $v !== null && $v !== ''));
    }

    public function viewName(): string
    {
        return TemplateRegistry::view($this->layout);
    }

    /** Layout sample, with this template's own sample text (design.sample) on top. */
    public function sampleContent(): array
    {
        $base = TemplateRegistry::layout($this->layout)['sample'] ?? [];
        $own = is_array($this->design['sample'] ?? null) ? $this->design['sample'] : [];

        return array_merge($base, $own);
    }
}
